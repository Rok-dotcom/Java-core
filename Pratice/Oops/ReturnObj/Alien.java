package ReturnObj;

public class Alien {
    private String name;
    private int points;

    // setters
    public void setName(String name){
        this.name = name;
    }
    public void setPoints(int points){
        this.points = points;
    }

    // getters
    public String getName(){
        return name;
    }
    public int getPoints(){
        return points;
    }
}
