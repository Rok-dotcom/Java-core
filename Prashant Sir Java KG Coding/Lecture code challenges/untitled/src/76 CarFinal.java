class CarFinal {
    final int noOfWheels;
    final String model;
    final String engineinLiters;

    public CarFinal(int noOfWheels, String model, String engineinLiters) {
        this.noOfWheels = noOfWheels;
        this.model = model;
        this.engineinLiters = engineinLiters;
        noOfWheels++;
    }
}
